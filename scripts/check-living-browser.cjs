// Chrome DevTools smoke test. No test/browser dependencies are added.
const { spawn } = require('node:child_process');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
let chrome, socket, server;
async function main() {
  server = http.createServer((req, res) => {
    let url = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    if (url.endsWith('/')) url += 'index.html';
    const file = path.resolve(root, 'out', '.' + url);
    if (!file.startsWith(path.join(root, 'out') + path.sep)) return res.writeHead(403).end();
    fs.readFile(file, (error, buffer) => {
      if (error) return res.writeHead(404).end();
      res.setHeader('Content-Type', ({ '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' })[path.extname(file)] || 'application/octet-stream');
      res.end(buffer);
    });
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const port = server.address().port;
  const profile = path.join(root, '.next', `collection-browser-${Date.now()}`);
  fs.mkdirSync(profile, { recursive: true });
  chrome = spawn(process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--remote-debugging-port=0', `--user-data-dir=${profile}`, 'about:blank'], { windowsHide: true, stdio: 'ignore' });
  let launchError;
  chrome.on('error', error => { launchError = error; });
  let debugPort;
  for (let i = 0; i < 100; i++) { if (launchError) throw launchError; try { debugPort = Number(fs.readFileSync(path.join(profile, 'DevToolsActivePort'), 'utf8').split('\n')[0]); break; } catch {} await pause(100); }
  assert.ok(debugPort, 'Chrome must start');
  const tabs = await (await fetch(`http://127.0.0.1:${debugPort}/json`)).json();
  socket = new WebSocket(tabs.find(tab => tab.type === 'page').webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }); });
  let nextId = 0;
  const pending = new Map(), errors = [];
  socket.addEventListener('message', event => { const message = JSON.parse(event.data); if (message.method === 'Runtime.exceptionThrown') errors.push(message.params.exceptionDetails.text); const job = pending.get(message.id); if (job) { pending.delete(message.id); clearTimeout(job.timer); message.error ? job.reject(new Error(message.error.message)) : job.resolve(message.result); } });
  const cdp = (method, params = {}) => new Promise((resolve, reject) => { const id = ++nextId; const timer = setTimeout(() => { pending.delete(id); reject(new Error(`Timed out: ${method}`)); }, 15000); pending.set(id, { resolve, reject, timer }); socket.send(JSON.stringify({ id, method, params })); });
  const evaluate = async expression => { const result = await cdp('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }); if (result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description || 'Evaluation failed'); return result.result.value; };
  const until = async expression => { for (let i = 0; i < 100; i++) { if (await evaluate(expression)) return; await pause(100); } throw new Error(`Timed out: ${expression}`); };
  const press = async (key, keyCode, modifiers = 0) => { await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key, code: key, windowsVirtualKeyCode: keyCode, modifiers }); await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key, code: key, windowsVirtualKeyCode: keyCode }); };
  const shot = async name => { await pause(400); const result = await cdp('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync(path.join(root, '.next', name), Buffer.from(result.data, 'base64')); };
  const base = `http://127.0.0.1:${port}`;
  await cdp('Runtime.enable');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await cdp('Page.navigate', { url: `${base}/collections/living-room/` });
  await until(`document.querySelectorAll('.lr-product-card').length===4 && Object.keys(document.querySelector('.lr-filter-button')).some(key=>key.startsWith('__reactProps'))`);
  await until(`Array.from(document.querySelectorAll('.lr-product-card img')).every(image=>image.complete && image.naturalWidth>0)`);
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.lr-product-grid')).gridTemplateColumns.split(' ').length`), 4);
  assert.equal(await evaluate(`document.documentElement.scrollWidth<=innerWidth`), true);
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('.lr-photo-dots')).every(group=>group.querySelectorAll('button').length===3)`), true);
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('.lr-product-card')).every(card=>card.querySelectorAll('img').length===4)`), true, 'One main image and three thumbnails per card; no automatic duplicate media');
  await shot('collection-desktop.png');
  await evaluate(`document.querySelector('.lr-photo-next').click()`);
  await until(`document.querySelector('.lr-photo-counter').textContent==='2 / 3'`);
  await evaluate(`document.querySelector('.lr-photo-dots button:last-child').click()`);
  await until(`document.querySelector('.lr-photo-counter').textContent==='3 / 3'`);
  await evaluate(`document.querySelector('.lr-filter-button').focus();document.querySelector('.lr-filter-button').click()`);
  await until(`document.querySelector('dialog').open`);
  await press('Tab', 9, 8);
  assert.equal(await evaluate(`document.querySelector('dialog').contains(document.activeElement)`), true);
  await evaluate(`Array.from(document.querySelectorAll('fieldset label')).find(label=>label.textContent==='Sofas').querySelector('input').click()`);
  await until(`document.querySelector('.lr-drawer-bottom p').textContent.startsWith('1 matching')`);
  await evaluate(`document.querySelector('.lr-drawer-bottom .lr-primary-button').click()`);
  await until(`!document.querySelector('dialog').open && document.querySelectorAll('.lr-product-card').length===1`);
  assert.equal(await evaluate(`document.activeElement===document.querySelector('.lr-filter-button')`), true);
  await evaluate(`Array.from(document.querySelectorAll('.lr-active-filters button')).find(button=>button.textContent==='Clear all').click();const s=document.querySelector('.lr-sort select');s.value='price-low';s.dispatchEvent(new Event('change',{bubbles:true}))`);
  await until(`document.querySelector('.lr-product-card h2').textContent.includes('Arc')`);
  // Follow the actual card link to the existing stable product route.
  await evaluate(`document.querySelector('.lr-product-card .lr-photo-link').click()`);
  await until(`!!document.querySelector('.lr-detail-info h1')`);
  assert.equal(await evaluate(`new URL(location.href).searchParams.get('id')`), 'arc-lamp');
  assert.equal(await evaluate(`document.querySelectorAll('.lr-thumbnails button').length`), 3);
  assert.ok(await evaluate(`parseFloat(getComputedStyle(document.querySelector('.lr-detail-info h1')).fontSize)>=32`), 'Product heading must retain its designed typography');
  await evaluate(`document.querySelector('.lr-thumbnails button:last-child').click()`);
  await until(`document.querySelector('.lr-photo-counter').textContent==='3 / 3'`);
  await shot('product-detail-desktop.png');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await pause(400);
  assert.equal(await evaluate(`document.documentElement.scrollWidth<=innerWidth`), true, 'Details page must fit mobile');
  await shot('product-detail-mobile.png');
  await cdp('Page.navigate', { url: `${base}/collections/living-room/?category=Chairs` });
  await until(`document.querySelectorAll('.lr-product-card').length===1 && document.querySelector('.lr-product-card h2')?.textContent.includes('Nola')`);
  await evaluate(`Array.from(document.querySelectorAll('.lr-active-filters button')).find(button=>button.textContent==='Clear all').click()`);
  await until(`document.querySelectorAll('.lr-product-card').length===4`);
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.lr-product-grid')).gridTemplateColumns.split(' ').length`), 2);
  assert.equal(await evaluate(`document.documentElement.scrollWidth<=innerWidth`), true, 'Collection must fit mobile');
  await shot('collection-mobile.png');
  await evaluate(`document.querySelector('.lr-filter-button').focus();document.querySelector('.lr-filter-button').click()`);
  await until(`document.querySelector('dialog').open`);
  await press('Escape', 27);
  await until(`!document.querySelector('dialog').open`);
  await cdp('Page.navigate', { url: `${base}/collections/living-room/?category=Coffee%20Tables` });
  await until(`!!document.querySelector('.lr-empty')`);
  await evaluate(`document.querySelector('.lr-empty button').click()`);
  await until(`document.querySelectorAll('.lr-product-card').length===4`);
  assert.deepEqual(errors, []);
  console.log('PASS: four-column desktop and two-column mobile layouts, three-photo controls, filters, counts, focus trap/return, sorting, real card-to-detail navigation, details gallery, category deep links, empty state and no browser exceptions.');
}
main().catch(error => { console.error(error); process.exitCode=1; }).finally(() => { socket?.close(); chrome?.kill(); server?.closeAllConnections(); server?.close(); });
